#include <unistd.h>
#include <stdlib.h>
#include "libft.h"

char	*ft_strnstr(const char *big, const char *little, size_t len)
{
	size_t	i;

	i = 0;
	if (*little == '\0')
		return ((char *)big);
	while (big[i])
	{
		if (ft_strncmp(big, little, len))
		{
			return ((char *)big + i);
		}
		i++;
	}
	return (NULL);
}
